/**
 * Generates docs/INVENTORY.md from the code: every page, API endpoint (method, guard, roles,
 * permission) and data model (and how it is tenant-scoped). Run `npm run inventory`; a unit test
 * fails when the committed file is out of date.
 */
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const walk = (dir: string, out: string[] = []) => {
  for (const n of readdirSync(dir)) {
    const p = path.join(dir, n);
    statSync(p).isDirectory() ? walk(p, out) : out.push(p);
  }
  return out;
};
const rel = (p: string) => path.relative(root, p).split(path.sep).join('/');

export function buildInventory(): string {
  const files = walk(path.join(root, 'src/app')).map(rel);

  // ---- Pages
  const pages = files
    .filter((f) => f.endsWith('/page.tsx'))
    .map((f) => {
      const seg = f.replace('src/app', '').replace('/page.tsx', '').split('/').filter((s) => s && !/^\(.*\)$/.test(s));
      const group = /\(admin\)/.test(f) ? 'Admin / manager console' : /\(salesperson\)/.test(f) ? 'Salesperson app' : /\(auth\)/.test(f) ? 'Sign-in' : 'Public';
      return { route: '/' + seg.join('/'), group };
    })
    .sort((a, b) => a.group.localeCompare(b.group) || a.route.localeCompare(b.route));

  // ---- API endpoints
  const endpoints: { path: string; method: string; guard: string }[] = [];
  const reexport = (src: string) => /export \{[^}]*\} from '([^']+)'/.exec(src)?.[1];
  for (const f of files.filter((x) => x.startsWith('src/app/api/') && x.endsWith('/route.ts'))) {
    let src = readFileSync(path.join(root, f), 'utf8');
    const re = reexport(src);
    if (re) {
      const target = path.join(path.dirname(path.join(root, f)), re + '.ts');
      const alt = path.join(path.dirname(path.join(root, f)), re, 'route.ts');
      for (const t of [target, alt]) {
        try {
          src = readFileSync(t, 'utf8');
          break;
        } catch {
          /* try next */
        }
      }
    }
    const apiPath =
      '/' +
      f
        .replace('src/app/', '')
        .replace('/route.ts', '')
        .replace(/\[([^\]]+)\]/g, ':$1');
    for (const m of src.matchAll(/export const (GET|POST|PUT|PATCH|DELETE)\b[\s\S]*?=\s*(authedRoute|publicRoute)(?:<[^>]*>)?\(([\s\S]{0,260})/g)) {
      const [, method, kind, head] = m;
      let guard = kind === 'publicRoute' ? 'public' : 'signed-in';
      if (kind === 'authedRoute') {
        const roles = /roles:\s*\[([^\]]*)\]/.exec(head)?.[1]?.replace(/Role\./g, '').replace(/\s/g, '');
        const perm = /managerPermission:\s*'([^']+)'/.exec(head)?.[1];
        if (roles) guard = roles.split(',').join(' / ') + (perm ? ` (manager needs ${perm})` : '');
        else if (perm) guard = `signed-in (manager needs ${perm})`;
      }
      endpoints.push({ path: apiPath, method, guard });
    }
    if (/export async function (GET|POST)\b/.test(src) || /export function (GET|POST)\b/.test(src)) {
      for (const m of src.matchAll(/export (?:async )?function (GET|POST)\b/g)) {
        if (!endpoints.some((e) => e.path === apiPath && e.method === m[1])) endpoints.push({ path: apiPath, method: m[1], guard: 'custom (see file)' });
      }
    }
  }
  endpoints.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method));

  // ---- Models
  const schema = readFileSync(path.join(root, 'prisma/schema.prisma'), 'utf8');
  const tenancy = readFileSync(path.join(root, 'src/lib/db/tenancy.ts'), 'utf8');
  const child = Object.fromEntries([...tenancy.matchAll(/^\s+(\w+): '(\w+)',$/gm)].map((m) => [m[1], m[2]]));
  const models = [...schema.matchAll(/^model (\w+) \{\n([\s\S]*?)^\}/gm)].map((m) => {
    const name = m[1];
    const direct = /^\s+tenantId\s/m.test(m[2]);
    const table = /@@map\("([^"]+)"\)/.exec(m[2])?.[1] ?? name;
    const scope = name === 'Tenant' ? 'global (the company list)' : direct ? 'tenantId column' : child[name] ? `through parent \`${child[name]}\`` : '— UNCLASSIFIED —';
    return { name, table, scope };
  });

  const t = (rows: string[][], head: string[]) => [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map((r) => `| ${r.join(' | ')} |`)].join('\n');
  return `<!-- Generated by \`npm run inventory\` from the code. Do not edit by hand. -->
# SalesGrid inventory

${pages.length} pages · ${endpoints.length} API endpoints · ${models.length} data models.

## Pages

${t(pages.map((p) => [`\`${p.route}\``, p.group]), ['Route', 'Interface'])}

## API endpoints

"signed-in" = any authenticated user (further scoped by role/team/ownership inside the handler). "SUPER_ADMIN" is always allowed by the route guard, so it is listed only when it is the sole role.

${t(endpoints.map((e) => [e.method, `\`${e.path}\``, e.guard]), ['Method', 'Path', 'Who may call it'])}

## Data models

${t(models.map((m) => [`\`${m.name}\``, `\`${m.table}\``, m.scope]), ['Model', 'Table', 'Company scoping'])}
`;
}

if (process.argv[1]?.endsWith('inventory.ts')) {
  writeFileSync(path.join(root, 'docs/INVENTORY.md'), buildInventory());
  console.log('docs/INVENTORY.md written');
}
